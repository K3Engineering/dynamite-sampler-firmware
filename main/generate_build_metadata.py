#!/usr/bin/env python
"""Generate build metadata in a C++ header format and output it on stdout."""

import argparse
import subprocess
import sys
import time


# All logs / warnings should be on stderr
def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def get_git_describe():
    # https://git-scm.com/docs/git-describe
    # Use git describe for a unique firmware version:
    # <latest tag>-<num commits from the tag>-<commit hash>-<dirty>
    # --always: if there isn't a tag, use the git hash.
    # --dirty: append -dirty if there are uncommited changes. Since the changes are not
    # commited, the next best thing is to make it apparent that the firmware has been changed.
    # --tags: use the non-annotated tags too, since github releases uses that.
    git_cmd = ["git", "describe", "--always", "--dirty", "--tags"]
    r = subprocess.run(git_cmd, capture_output=True, check=True)

    return r.stdout.strip().decode("utf-8")


def generate_build_metadata(git_describe: str, is_debug: bool, idf_version: str):

    # Construct Firmware Revision String (0x2A26)
    fw_revision = git_describe
    if is_debug:
        fw_revision += "+debug"

    # Construct Software Revision String (0x2A28)
    sw_revision = f"ESP-IDF {idf_version}"

    output = f"""/*
This file was autogenerated by main/generate_build_metadata.py at: {time.strftime("%Y-%m-%d %H:%M:%S")}
Invoked with: {sys.argv[1:]}
*/

#ifndef _BUILD_METADATA_H
#define _BUILD_METADATA_H

constexpr char FW_REVISION_STR[] = "{fw_revision}";
constexpr char SW_REVISION_STR[] = "{sw_revision}";
constexpr uint32_t BUILD_TIME = {int(time.time())};

#endif // _BUILD_METADATA_H"""

    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate build metadata header.")
    parser.add_argument(
        "--sdkconfig-debug",
        required=True,
        nargs="?",  # the value could be empty if it is release
        const="",  # so in that case use empty string
        help="CONFIG_COMPILER_OPTIMIZATION_DEBUG value",
    )
    parser.add_argument("--idf-version", required=True, help="IDF_VER value")
    args = parser.parse_args()

    is_debug = args.sdkconfig_debug.lower() in ("y", "1", "true")
    git_describe = get_git_describe()
    meta = generate_build_metadata(
        git_describe=git_describe, is_debug=is_debug, idf_version=args.idf_version
    )
    print(meta)
